import { useEffect } from 'preact/hooks';

// プライバシーについて（#/privacy）：内容は実装（worker/src・web/src/storage/local.ts・各画面）と公開の構成（README）に合わせて更新すること
export function Privacy() {
  useEffect(() => {
    const before = document.title;
    document.title = 'プライバシーについて｜曲のしおり';
    return () => { document.title = before; };
  }, []);

  return (
    <main class="page narrow">
      <header class="hero">
        <h1>プライバシーについて</h1>
        <p>曲のしおりが扱う情報と、その保存・公開の範囲をまとめています。</p>
      </header>

      <article class="card">
        <h2>アカウントはありません</h2>
        <p>登録やログインはなく、氏名・メールアドレス・電話番号などはお預かりしません。曲メモは、作成時に発行される閲覧URL・管理キー・編集キーで見たり編集したりします。</p>

        <h2>音源ファイルは送信しません</h2>
        <p>選んだ音源ファイルは、この端末の中だけで解析・再生し、サーバーへは送信しません。サーバーやこのブラウザに音源ファイルを保存することもありません。</p>

        <h2>保存する情報</h2>
        <ul class="points">
          <li>曲メモに入力・解析した内容（曲名、アーティスト名、区間・小節数・テンポ、コード進行、メモ、YouTube の動画など）</li>
          <li>更新のときに書いた変更メモと、直近10回分の過去の内容</li>
          <li>作成・更新日時、保存期限、共有の状態</li>
          <li>キーの照合用データ（キーそのものではなく、元に戻せない形に変換した値）</li>
        </ul>
        <p>入力欄には個人情報を書かないでください。</p>

        <h2>見られる人</h2>
        <ul class="points">
          <li>閲覧URLを知っている人は、誰でも曲メモの内容と変更メモを見られます。</li>
          <li>編集キーを知っている人は、構成を直して保存できます。管理キーを知っている人は、削除や共有の管理を含め、すべての操作ができます。</li>
          <li>URLやキーは転送されると、転送先の人も同じように使えます。</li>
        </ul>
        <p>閲覧ページは検索エンジンに載らないよう設定していますが、アクセスを制限するものではありません。共有の停止や削除をしても、すでに保存・転載・撮影された内容は取り消せません。</p>

        <h2>保存期間と削除</h2>
        <p>曲メモは、最後の保存（または保存期間の延長）から180日後に自動で削除します。管理キーで開けば、いつでも削除できます。削除すると、過去の内容も含めてすべて消え、閲覧URLも使えなくなります。</p>

        <h2>アクセス情報</h2>
        <p>短時間に操作が集中するのを防ぐため、作成・保存などのときに接続元のIPアドレスを秘密の値と組み合わせて元に戻せない形に変換し、1時間単位の回数だけを記録します（IPアドレスそのものは保存しません）。この記録は毎日の定期処理で削除します（最長で1日程度残ります）。</p>
        <p>また、改善のため、自動解析の成否や所要時間、曲の長さ、手動での作成、区間のくり返し再生、YouTube の動画の利用などの操作を記録しています。記録するのは操作の種類と日時、端末の種類（スマートフォンかパソコンか）、このブラウザで作った匿名の識別子で、曲名などの入力内容、IPアドレス、どの曲メモかは記録しません。この記録は約90日で削除します。Cookie や広告による追跡は行っていません。</p>

        <h2>利用している外部サービス</h2>
        <ul class="points">
          <li>GitHub Pages（画面の配信）</li>
          <li>Cloudflare Workers・D1（保存と読み出し）</li>
          <li>YouTube（動画を設定した曲メモで、動画を表示したときのみ。プライバシー強化モードを使います）</li>
          <li>YouTube Data API（「曲を検索」を押したときのみ。サーバーから問い合わせます）</li>
          <li>iTunes Search API（「曲を検索」を押したときのみ）</li>
          <li>GetSongBPM・Deezer（BPMを調べたときのみ。サーバーから問い合わせます）</li>
        </ul>
        <p>ページを開いたり動画を表示したりすると、そのサービスに通常の通信情報（IPアドレス、ブラウザの種類など）が送られます。「曲を検索」では曲名とアーティスト名が Google（YouTube）と Apple に、BPMを調べると曲名とアーティスト名が GetSongBPM・Deezer に送られます（YouTube と BPM の問い合わせはサーバーから行うので、IPアドレスは送られません）。各サービスでの取り扱いは、それぞれの方針に従います。</p>

        <h2>このブラウザに保存する情報</h2>
        <p>入力途中の下書き（30日まで）、編集した曲メモの一覧、発行したキーと編集の記憶（記憶を選んだとき）、表示や音量の設定、匿名の識別子を、このブラウザ（localStorage・IndexedDB）に保存します。共用の端末では、使い終わったらブラウザのサイトデータを削除してください。</p>

        <p class="sub">2026年10月23日 制定</p>
      </article>
      <a href="#/">トップへ</a>
    </main>
  );
}
